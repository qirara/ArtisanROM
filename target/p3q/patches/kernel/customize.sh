# Stock kernel (P3Q_KERNEL=stock, default without a custom kernel) or the KernelSU Next enabled kernel
# (P3Q_KERNEL=kernelsu), built with target/p3q/kernel/build_kernel.sh.
# The kernel artifacts are read from $P3Q_KERNEL_DIR (defaults to $OUT_DIR/kernel/p3q).
#
# - boot.img: kernel replaced with Image + lahaina base DTBs, stock header/ramdisk kept
# - dtbo.img: replaced with the p3q board overlays built from the same tree
# - /vendor/lib/modules: stock modules replaced with the ones built from the same tree
#   (the kernel is not ABI compatible with the stock modules), the ones that are built-in are removed
#   and modules.dep/modules.alias/modules.softdep/modules.load are updated accordingly
# - vendor_boot.img: untouched, the drivers shipped in it as GKI modules are built-in

KERNEL_DIR="${P3Q_KERNEL_DIR:-$OUT_DIR/kernel/p3q}"

# P3Q_KERNEL=stock keeps the stock kernel, dtbo and modules (no KernelSU). It is also the default
# when no custom kernel was built.
if [[ "$P3Q_KERNEL" == "stock" ]] || { [ ! "$P3Q_KERNEL" ] && [ ! -f "$KERNEL_DIR/Image-dtb" ]; }; then
    LOG "- Keeping the stock kernel"

    # The ROM partitions are built as $TARGET_OS_FILE_SYSTEM_TYPE images, the stock kernel must mount them
    if [[ "$TARGET_OS_FILE_SYSTEM_TYPE" == "erofs" ]]; then
        if [ -d "$TMP_DIR" ]; then
            EVAL "rm -rf \"$TMP_DIR\""
        fi
        EVAL "mkdir -p \"$TMP_DIR\""
        if ! MKBOOTIMG_ARGS="$(unpack_bootimg --boot_img "$WORK_DIR/kernel/boot.img" --out "$TMP_DIR/boot" 2>&1)"; then
            ABORT "Failed to extract boot.img\n\n$MKBOOTIMG_ARGS"
        fi
        if [[ "$(READ_BYTES_AT "$TMP_DIR/boot/kernel" "0" "2")" == "8b1f" ]]; then
            EVAL "gzip -dc \"$TMP_DIR/boot/kernel\" > \"$TMP_DIR/Image\""
        else
            EVAL "mv -f \"$TMP_DIR/boot/kernel\" \"$TMP_DIR/Image\""
        fi
        if ! grep -q -a -F "erofs" "$TMP_DIR/Image"; then
            ABORT "The stock kernel has no EROFS support, the ROM partitions would not mount.\n\nUse TARGET_OS_FILE_SYSTEM_TYPE=\"ext4\" or build the custom kernel (P3Q_KERNEL=kernelsu)."
        fi
        LOG "- The stock kernel supports EROFS"
        EVAL "rm -rf \"$TMP_DIR\""
    fi

    unset KERNEL_DIR MKBOOTIMG_ARGS
    return 0
fi

for f in "Image-dtb" "dtbo.img" "kernel.release"; do
    if [ ! -f "$KERNEL_DIR/$f" ]; then
        ABORT "File not found: $KERNEL_DIR/$f\n\nBuild the kernel first with:\n  target/p3q/kernel/build_kernel.sh <kernel source dir> $KERNEL_DIR"
    fi
done

if [ ! -f "$WORK_DIR/kernel/boot.img" ]; then
    ABORT "File not found: ${WORK_DIR//$SRC_DIR\//}/kernel/boot.img"
fi

if [ -d "$TMP_DIR" ]; then
    EVAL "rm -rf \"$TMP_DIR\""
fi
EVAL "mkdir -p \"$TMP_DIR\""

LOG_STEP_IN "- Installing kernel $(cat "$KERNEL_DIR/kernel.release")"

LOG "- Extracting boot.img"
EVAL "cp -a \"$WORK_DIR/kernel/boot.img\" \"$TMP_DIR/boot.img\""
if ! MKBOOTIMG_ARGS="$(unpack_bootimg --boot_img "$TMP_DIR/boot.img" --out "$TMP_DIR/boot" --format mkbootimg 2>&1)"; then
    ABORT "Failed to extract boot.img\n\n$MKBOOTIMG_ARGS"
fi
EVAL "rm -f \"$TMP_DIR/boot.img\""

LOG "- Replacing kernel image"
EVAL "cp -a \"$KERNEL_DIR/Image-dtb\" \"$TMP_DIR/boot/kernel\""

LOG "- Repacking boot.img"
EVAL "mkbootimg $MKBOOTIMG_ARGS -o \"$TMP_DIR/new-boot.img\""
echo -n "SEANDROIDENFORCE" >> "$TMP_DIR/new-boot.img"
EVAL "mv -f \"$TMP_DIR/new-boot.img\" \"$WORK_DIR/kernel/boot.img\""

LOG "- Replacing dtbo.img"
EVAL "cp -a \"$KERNEL_DIR/dtbo.img\" \"$WORK_DIR/kernel/dtbo.img\""

if [ -d "$KERNEL_DIR/modules" ]; then
    MODULES_DIR="$WORK_DIR/vendor/lib/modules"

    LOG_STEP_IN "- Replacing kernel modules in /vendor/lib/modules"
    EVAL "mkdir -p \"$TMP_DIR/root/vendor/lib/modules\""
    while IFS= read -r f; do
        MODULE="$(basename "$f")"
        if [ -f "$MODULES_DIR/$MODULE" ]; then
            EVAL "cp -a \"$f\" \"$TMP_DIR/root/vendor/lib/modules/$MODULE\""
            ADD_TO_WORK_DIR "$TMP_DIR/root" "vendor" "lib/modules/$MODULE" 0 0 644 "u:object_r:vendor_file:s0"
        fi
    done < <(find "$KERNEL_DIR/modules" -maxdepth 1 -type f -name "*.ko" | LC_ALL=C sort)

    # The stock modules that have not been rebuilt are built-in in this kernel (eg. touchscreen/input booster drivers),
    # they would only fail to load and break modprobe for the modules depending on them in the stock modules.dep
    while IFS= read -r f; do
        MODULE="$(basename "$f")"
        if [ ! -f "$KERNEL_DIR/modules/$MODULE" ]; then
            DELETE_FROM_WORK_DIR "vendor" "lib/modules/$MODULE"
        fi
    done < <(find "$MODULES_DIR" -maxdepth 1 -type f -name "*.ko" | LC_ALL=C sort)

    # modules.dep/modules.alias/modules.softdep generated by depmod for the new modules,
    # using the same module path format as the stock modules.dep
    if [ -f "$KERNEL_DIR/modules/modules.dep" ]; then
        PREFIX=""
        if grep -q "^/vendor/lib/modules/" "$MODULES_DIR/modules.dep" 2> /dev/null; then
            PREFIX="/vendor/lib/modules/"
        fi
        LOG "- Generating /vendor/lib/modules/modules.dep"
        while IFS= read -r LINE; do
            MODULE="$(cut -d ":" -f 1 <<< "$LINE")"
            if [ -f "$MODULES_DIR/$MODULE" ]; then
                sed -E "s|([^ :]+\.ko)|$PREFIX\1|g" <<< "$LINE"
            fi
        done < "$KERNEL_DIR/modules/modules.dep" > "$TMP_DIR/root/vendor/lib/modules/modules.dep"
        ADD_TO_WORK_DIR "$TMP_DIR/root" "vendor" "lib/modules/modules.dep" 0 0 644 "u:object_r:vendor_file:s0"
    fi
    for f in "modules.alias" "modules.softdep"; do
        if [ -f "$KERNEL_DIR/modules/$f" ]; then
            LOG "- Replacing /vendor/lib/modules/$f"
            EVAL "cp -a \"$KERNEL_DIR/modules/$f\" \"$TMP_DIR/root/vendor/lib/modules/$f\""
            ADD_TO_WORK_DIR "$TMP_DIR/root" "vendor" "lib/modules/$f" 0 0 644 "u:object_r:vendor_file:s0"
        fi
    done

    # Drop the deleted modules from the load list
    if [ -f "$MODULES_DIR/modules.load" ]; then
        LOG "- Updating /vendor/lib/modules/modules.load"
        while IFS= read -r LINE; do
            if [ -f "$MODULES_DIR/$(basename "$LINE")" ]; then
                echo "$LINE"
            fi
        done < "$MODULES_DIR/modules.load" > "$TMP_DIR/root/vendor/lib/modules/modules.load"
        ADD_TO_WORK_DIR "$TMP_DIR/root" "vendor" "lib/modules/modules.load" 0 0 644 "u:object_r:vendor_file:s0"
    fi

    # vendor_modprobe.sh switches to /vendor/lib/modules/5.4-gki when the first module it tries from
    # /vendor/lib/modules does not load. Those are stock modules, they can only fail with this kernel
    # ("disagrees about version of symbol module_layout"): always use the rebuilt ones
    if grep -q "^GKI_MOD_PATH=\"/vendor/lib/modules/5.4-gki\"$" "$WORK_DIR/vendor/bin/vendor_modprobe.sh" 2> /dev/null; then
        LOG "- Patching /vendor/bin/vendor_modprobe.sh"
        sed -i "s|^GKI_MOD_PATH=.*|GKI_MOD_PATH=\"/vendor/lib/modules\"|" "$WORK_DIR/vendor/bin/vendor_modprobe.sh"
    fi
    LOG_STEP_OUT
fi

LOG_STEP_OUT

EVAL "rm -rf \"$TMP_DIR\""

unset KERNEL_DIR LINE MODULE MODULES_DIR MKBOOTIMG_ARGS PREFIX
